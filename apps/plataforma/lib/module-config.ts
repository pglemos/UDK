const statusOptions = (...values: string[]): SelectOption[] =>
  values.map((value) => ({
    value,
    label:
      statusLabels[value] ??
      value.replaceAll("_", " ").replace(/\b\w/g, (letter) => letter.toUpperCase()),
  }));

type Named = { sport_name?: string | null; full_name?: string | null } | null | undefined;
const nameOf = (driver: unknown) => {
  const value = driver as Named;
  return value?.sport_name || value?.full_name || "sem piloto";
};
const stageOf = (stage: unknown) => (stage as { title?: string } | null)?.title ?? "sem etapa";

function penaltyLabel(row: Record<string, unknown>): string {
  const summary = String(row.summary ?? "").replace(/\s*\(.*?\)\.?$/, "");
  return `${stageOf(row.stage)} · ${nameOf(row.driver)} · ${String(row.code ?? "")} — ${summary.slice(0, 70)}`;
}

function incidentLabel(row: Record<string, unknown>): string {
  const lap = row.lap_number ? ` · volta ${String(row.lap_number)}` : "";
  return `${stageOf(row.stage)} · ${nameOf(row.driver)} · ${String(row.incident_type ?? "")}${lap}`;
}

const relation = (
  key: string,
  label: string,
  table: string,
  labelColumn: string,
  required = true,
): ModuleField => ({
  key,
  label,
  kind: "relation",
  required,
  relation: { table, labelColumn },
});

// Sessão pertence a uma etapa: results e kart_assignments têm chave estrangeira
// composta (stage_id, session_id) -> sessions(stage_id, id). Sem o filtro, o
// formulário deixa escolher uma sessão de outra etapa e o insert falha com 409.
const sessionOfStage = (required = false): ModuleField => ({
  key: "session_id",
  label: "Sessão",
  kind: "relation",
  required,
  relation: {
    table: "sessions",
    labelColumn: "name",
    dependsOn: { field: "stage_id", column: "stage_id" },
  },
});

