export type FieldKind =
  | "text"
  | "textarea"
  | "number"
  | "currency"
  | "datetime"
  | "date"
  | "select"
  | "relation"
  | "checkbox"
  | "json"
  | "file";

export type SelectOption = {
  label: string;
  value: string;
};

export type RelationConfig = {
  table: string;
  labelColumn: string;
  valueColumn?: string;
  filters?: Record<string, string | number | boolean>;
  /**
   * Restringe as opções ao que pertence ao valor escolhido em outro campo do
   * formulário. Sessão só faz sentido dentro da etapa selecionada, e o banco
   * cobra isso com uma chave estrangeira composta.
   */
  dependsOn?: { field: string; column: string };
  /** Select com relações (ex.: "id,code,stage:stages(title)") quando o rótulo junta várias colunas. */
  labelSelect?: string;
  formatLabel?: (row: Record<string, unknown>) => string;
  /** Campos do formulário preenchidos ao escolher a opção (ex.: piloto da penalidade). */
  fill?: (row: Record<string, unknown>) => Record<string, unknown>;
};

export type FieldSuggestion = {
  value: string;
  label: string;
  /** Outros campos preenchidos quando esta sugestão é escolhida. */
  fill?: Record<string, string | number | boolean>;
};

export type ModuleField = {
  key: string;
  label: string;
  /** Dica curta mostrada embaixo do campo no formulário. */
  help?: string;
  kind: FieldKind;
  required?: boolean;
  readOnly?: boolean;
  placeholder?: string;
  options?: SelectOption[];
  relation?: RelationConfig;
  storageBucket?: string;
  accept?: string;
  /**
   * Campos que não podem ser preenchidos junto com este. O banco cobra alguns
   * desses pares com CHECK — um kart é de um piloto ou de uma equipe, nunca
   * dos dois — e sem aviso o formulário só devolve a recusa depois de salvar.
   */
  exclusiveWith?: string[];
  /** Lista de valores sugeridos (do regulamento); continua aceitando texto livre. */
  suggestions?: FieldSuggestion[];
};

export type ModuleAction = {
  key: string;
  label: string;
  rpc: string;
  parameterMap: Record<string, string>;
  confirmation: string;
};

export type ModuleConfig = {
  key: string;
  label: string;
  description: string;
  table: string;
  singular: string;
  titleColumn: string;
  orderBy?: string;
  ascending?: boolean;
  fields: ModuleField[];
  readOnly?: boolean;
  createOnly?: boolean;
  actions?: ModuleAction[];
  /** Colunas da listagem, em ordem; sem isso a tabela mostra os 5 primeiros campos. */
  tableColumns?: string[];
  /** Texto do estado vazio quando os registros não são criados pela organização. */
  emptyHint?: string;
};

